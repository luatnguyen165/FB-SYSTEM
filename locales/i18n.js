function t(key, lang = 'vi', fallback = null) {
    const dict = translations[lang] || translations.vi;
    return dict[key] !== undefined ? dict[key] : (fallback !== null ? fallback : key);
}

function getLang(req) {
    if (req.user && req.user.language) return req.user.language;
    if (req.session && req.session.user && req.session.user.language) return req.session.user.language;
    return 'vi';
}

module.exports = { translations, t, getLang };
